"""Rebuild everything that is generated from PetalReader.html.

PetalReader.html is the one source of truth. After editing it, run:

    python tools/build.py

This refreshes:
  * vscode-extension/media/   (the preview player, its styles and a copy of the app)
  * vscode-extension/*.vsix   (the installable VS Code add-on)
  * docs/                     (the installable phone / web version, hosted by GitHub Pages)
"""
import hashlib
import html
import json
import pathlib
import shutil
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
APP = ROOT / "PetalReader.html"
ASSETS = ROOT / "assets"
EXT = ROOT / "vscode-extension"
PHONE = ROOT / "docs"  # served by GitHub Pages (main branch, /docs folder)


def section(text, begin, end):
    i = text.index(begin)
    j = text.index(end, i) + len(end)
    return text[i:j]


def build_extension(app_html):
    core = section(app_html, "/* ==PETAL-CORE-BEGIN== */", "/* ==PETAL-CORE-END== */")
    track_css = section(app_html, "/* ==PETAL-TRACK-CSS-BEGIN== */", "/* ==PETAL-TRACK-CSS-END== */")
    media = EXT / "media"
    media.mkdir(exist_ok=True)
    header = "/* Generated by tools/build.py from PetalReader.html and src/preview-ui.js. Do not edit. */\n"
    ui_js = (EXT / "src" / "preview-ui.js").read_text(encoding="utf-8")
    (media / "petal-preview.js").write_text(header + core + "\n\n" + ui_js, encoding="utf-8")
    css = (EXT / "src" / "preview.css").read_text(encoding="utf-8")
    (media / "petal-preview.css").write_text(header + css.replace("@TRACK@", track_css), encoding="utf-8")
    shutil.copyfile(APP, media / "app.html")
    shutil.copyfile(ASSETS / "icon-128.png", media / "icon.png")


CONTENT_TYPES = """<?xml version="1.0" encoding="utf-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension=".json" ContentType="application/json"/>
<Default Extension=".js" ContentType="application/javascript"/>
<Default Extension=".css" ContentType="text/css"/>
<Default Extension=".html" ContentType="text/html"/>
<Default Extension=".png" ContentType="image/png"/>
<Default Extension=".md" ContentType="text/markdown"/>
<Default Extension=".txt" ContentType="text/plain"/>
<Default Extension=".vsixmanifest" ContentType="text/xml"/>
</Types>
"""


def vsix_manifest(pkg):
    e = lambda s: html.escape(str(s), quote=True)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<PackageManifest Version="2.0.0" xmlns="http://schemas.microsoft.com/developer/vsx-schema/2011" xmlns:d="http://schemas.microsoft.com/developer/vsx-schema-design/2011">
  <Metadata>
    <Identity Language="en-US" Id="{e(pkg['name'])}" Version="{e(pkg['version'])}" Publisher="{e(pkg['publisher'])}" />
    <DisplayName>{e(pkg['displayName'])}</DisplayName>
    <Description xml:space="preserve">{e(pkg['description'])}</Description>
    <Tags>{e(','.join(pkg.get('keywords', [])))}</Tags>
    <Categories>{e(','.join(pkg.get('categories', [])))}</Categories>
    <GalleryFlags>Public</GalleryFlags>
    <Properties>
      <Property Id="Microsoft.VisualStudio.Code.Engine" Value="{e(pkg['engines']['vscode'])}" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionDependencies" Value="" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionPack" Value="" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionKind" Value="{e(','.join(pkg.get('extensionKind', ['workspace'])))}" />
      <Property Id="Microsoft.VisualStudio.Code.LocalizedLanguages" Value="" />
      <Property Id="Microsoft.VisualStudio.Services.GitHubFlavoredMarkdown" Value="true" />
      <Property Id="Microsoft.VisualStudio.Services.Content.Pricing" Value="Free" />
    </Properties>
    <License>extension/LICENSE.txt</License>
    <Icon>extension/media/icon.png</Icon>
  </Metadata>
  <Installation>
    <InstallationTarget Id="Microsoft.VisualStudio.Code" />
  </Installation>
  <Dependencies />
  <Assets>
    <Asset Type="Microsoft.VisualStudio.Code.Manifest" Path="extension/package.json" Addressable="true" />
    <Asset Type="Microsoft.VisualStudio.Services.Content.Details" Path="extension/README.md" Addressable="true" />
    <Asset Type="Microsoft.VisualStudio.Services.Content.License" Path="extension/LICENSE.txt" Addressable="true" />
    <Asset Type="Microsoft.VisualStudio.Services.Icons.Default" Path="extension/media/icon.png" Addressable="true" />
  </Assets>
</PackageManifest>
"""


def package_vsix():
    pkg = json.loads((EXT / "package.json").read_text(encoding="utf-8"))
    files = ["package.json", "extension.js", "README.md", "LICENSE.txt",
             "media/petal-preview.js", "media/petal-preview.css", "media/app.html", "media/icon.png"]
    for old in EXT.glob("*.vsix"):
        old.unlink()
    out = EXT / f"{pkg['name']}-{pkg['version']}.vsix"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", CONTENT_TYPES)
        z.writestr("extension.vsixmanifest", vsix_manifest(pkg))
        for f in files:
            z.write(EXT / f, "extension/" + f)
    return out


PWA_HEAD = """<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Petal Reader">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">"""

SERVICE_WORKER = """// Petal Reader offline cache. A new version is picked up automatically after an update.
const CACHE = 'petal-reader-%s';
const FILES = ['./', './index.html', './manifest.webmanifest', './icon-192.png', './icon-512.png', './icon-maskable-512.png', './apple-touch-icon.png'];
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true })
    .then((hit) => hit || fetch(e.request).catch(() => caches.match('./index.html'))));
});
"""


def build_phone(app_html):
    PHONE.mkdir(exist_ok=True)
    page = app_html.replace("<!--PWA-->", PWA_HEAD, 1)
    (PHONE / "index.html").write_text(page, encoding="utf-8")
    for name in ["icon-192.png", "icon-512.png", "icon-maskable-512.png", "apple-touch-icon.png"]:
        shutil.copyfile(ASSETS / name, PHONE / name)
    manifest = {
        "name": "Petal Reader",
        "short_name": "Petal Reader",
        "description": "Read any text or Markdown aloud with word highlighting, chapters and double-click to jump.",
        "start_url": "./",
        "scope": "./",
        "display": "standalone",
        "orientation": "any",
        "background_color": "#15121f",
        "theme_color": "#15121f",
        "icons": [
            {"src": "icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "icon-512.png", "sizes": "512x512", "type": "image/png"},
            {"src": "icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
        ],
    }
    (PHONE / "manifest.webmanifest").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    version = hashlib.sha1(page.encode("utf-8")).hexdigest()[:10]
    (PHONE / "sw.js").write_text(SERVICE_WORKER % version, encoding="utf-8")
    (PHONE / ".nojekyll").write_text("", encoding="utf-8")


def main():
    app_html = APP.read_text(encoding="utf-8")
    build_extension(app_html)
    vsix = package_vsix()
    build_phone(app_html)
    print("Built:")
    print("  ", vsix.relative_to(ROOT))
    print("  ", (EXT / "media").relative_to(ROOT))
    print("  ", PHONE.relative_to(ROOT))


if __name__ == "__main__":
    main()
