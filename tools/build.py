"""Build every generated Petal Reader artifact reproducibly.

Files under src/ are the source of truth. Run python tools/build.py to refresh
the committed one-file app, PWA, extension media, and VSIX, or add --check to
verify every generated artifact without changing the checkout.
"""
import argparse
import hashlib
import html
import json
import pathlib
import shutil
import tempfile
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
FIXED_ZIP_TIME = (1980, 1, 1, 0, 0, 0)
SOURCE_MANIFEST = [
    ("@@PETAL_APP_CSS@@", "src/styles/app.css"),
    ("@@PETAL_CORE_JS@@", [
        "src/providers/speech-provider.js",
        "src/providers/browser-speech-provider.js",
        "src/core/reader.js",
    ]),
    ("@@PETAL_APP_JS@@", "src/app/app.js"),
]
VSIX_FILES = [
    "package.json",
    "extension.js",
    "README.md",
    "LICENSE.txt",
    "media/petal-preview.js",
    "media/petal-preview.css",
    "media/app.html",
    "media/icon.png",
]


def source_text(path):
    text = path.read_text(encoding="utf-8")
    if "\r" in text:
        raise ValueError(f"source must use LF line endings: {path}")
    return text


def write_text(path, text):
    with path.open("w", encoding="utf-8", newline="\n") as output:
        output.write(text)


def build_app(root):
    template_path = root / "src" / "app" / "template.html"
    page = source_text(template_path)
    seen_paths = set()
    for placeholder, relative_paths in SOURCE_MANIFEST:
        count = page.count(placeholder)
        if count != 1:
            raise ValueError(
                f"expected exactly one {placeholder} in {template_path}, found {count}"
            )
        if isinstance(relative_paths, str):
            relative_paths = [relative_paths]
        duplicates = seen_paths.intersection(relative_paths)
        if duplicates:
            raise ValueError(f"duplicate source manifest entry: {sorted(duplicates)}")
        seen_paths.update(relative_paths)
        source = "\n".join(source_text(root / relative_path) for relative_path in relative_paths)
        page = page.replace(placeholder, source, 1)
    write_text(root / "PetalReader.html", page)
    return page


def section(text, begin, end):
    i = text.index(begin)
    j = text.index(end, i) + len(end)
    return text[i:j]


def build_extension(root, app_html):
    app = root / "PetalReader.html"
    assets = root / "assets"
    ext = root / "vscode-extension"
    media = ext / "media"
    media.mkdir(exist_ok=True)
    core = section(app_html, "/* ==PETAL-CORE-BEGIN== */", "/* ==PETAL-CORE-END== */")
    track_css = section(app_html, "/* ==PETAL-TRACK-CSS-BEGIN== */", "/* ==PETAL-TRACK-CSS-END== */")
    header = "/* Generated by tools/build.py from PetalReader.html and src/preview-ui.js. Do not edit. */\n"
    ui_js = (ext / "src" / "preview-ui.js").read_text(encoding="utf-8")
    write_text(media / "petal-preview.js", header + core + "\n\n" + ui_js)
    css = (ext / "src" / "preview.css").read_text(encoding="utf-8")
    write_text(media / "petal-preview.css", header + css.replace("@TRACK@", track_css))
    shutil.copyfile(app, media / "app.html")
    shutil.copyfile(assets / "icon-128.png", media / "icon.png")


CONTENT_TYPES = """<?xml version="1.0" encoding="utf-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension=".json" ContentType="application/json"/>
<Default Extension=".js" ContentType="application/javascript"/>
<Default Extension=".css" ContentType="text/css"/>
<Default Extension=".html" ContentType="text/html"/>
<Default Extension=".png" ContentType="image/png"/>
<Default Extension=".md" ContentType="text/markdown"/>
<Default Extension=".txt" ContentType="text/plain"/>
<Default Extension=".vsixmanifest" ContentType="text/xml"/>
</Types>
"""


def vsix_manifest(pkg):
    e = lambda s: html.escape(str(s), quote=True)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<PackageManifest Version="2.0.0" xmlns="http://schemas.microsoft.com/developer/vsx-schema/2011" xmlns:d="http://schemas.microsoft.com/developer/vsx-schema-design/2011">
  <Metadata>
    <Identity Language="en-US" Id="{e(pkg['name'])}" Version="{e(pkg['version'])}" Publisher="{e(pkg['publisher'])}" />
    <DisplayName>{e(pkg['displayName'])}</DisplayName>
    <Description xml:space="preserve">{e(pkg['description'])}</Description>
    <Tags>{e(','.join(pkg.get('keywords', [])))}</Tags>
    <Categories>{e(','.join(pkg.get('categories', [])))}</Categories>
    <GalleryFlags>Public</GalleryFlags>
    <Properties>
      <Property Id="Microsoft.VisualStudio.Code.Engine" Value="{e(pkg['engines']['vscode'])}" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionDependencies" Value="" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionPack" Value="" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionKind" Value="{e(','.join(pkg.get('extensionKind', ['workspace'])))}" />
      <Property Id="Microsoft.VisualStudio.Code.LocalizedLanguages" Value="" />
      <Property Id="Microsoft.VisualStudio.Services.GitHubFlavoredMarkdown" Value="true" />
      <Property Id="Microsoft.VisualStudio.Services.Content.Pricing" Value="Free" />
    </Properties>
    <License>extension/LICENSE.txt</License>
    <Icon>extension/media/icon.png</Icon>
  </Metadata>
  <Installation>
    <InstallationTarget Id="Microsoft.VisualStudio.Code" />
  </Installation>
  <Dependencies />
  <Assets>
    <Asset Type="Microsoft.VisualStudio.Code.Manifest" Path="extension/package.json" Addressable="true" />
    <Asset Type="Microsoft.VisualStudio.Services.Content.Details" Path="extension/README.md" Addressable="true" />
    <Asset Type="Microsoft.VisualStudio.Services.Content.License" Path="extension/LICENSE.txt" Addressable="true" />
    <Asset Type="Microsoft.VisualStudio.Services.Icons.Default" Path="extension/media/icon.png" Addressable="true" />
  </Assets>
</PackageManifest>
"""


def zip_info(name):
    info = zipfile.ZipInfo(name, FIXED_ZIP_TIME)
    info.compress_type = zipfile.ZIP_DEFLATED
    info.create_system = 3
    info.external_attr = 0o100644 << 16
    return info


def package_vsix(root):
    ext = root / "vscode-extension"
    pkg = json.loads((ext / "package.json").read_text(encoding="utf-8"))
    for old in ext.glob("*.vsix"):
        old.unlink()
    out = ext / f"{pkg['name']}-{pkg['version']}.vsix"
    entries = {
        "[Content_Types].xml": CONTENT_TYPES.encode("utf-8"),
        "extension.vsixmanifest": vsix_manifest(pkg).encode("utf-8"),
    }
    entries.update({f"extension/{name}": (ext / name).read_bytes() for name in VSIX_FILES})
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name in sorted(entries):
            archive.writestr(zip_info(name), entries[name])
    return out


PWA_HEAD = """<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Petal Reader">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">"""

SERVICE_WORKER = """// Petal Reader offline cache. A new version is picked up automatically after an update.
const CACHE = 'petal-reader-%s';
const FILES = ['./', './index.html', './manifest.webmanifest', './icon-192.png', './icon-512.png', './icon-maskable-512.png', './apple-touch-icon.png'];
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true })
    .then((hit) => hit || fetch(e.request).catch(() => caches.match('./index.html'))));
});
"""


def build_phone(root, app_html):
    assets = root / "assets"
    phone = root / "docs"
    phone.mkdir(exist_ok=True)
    page = app_html.replace("<!--PWA-->", PWA_HEAD, 1)
    write_text(phone / "index.html", page)
    for name in ["icon-192.png", "icon-512.png", "icon-maskable-512.png", "apple-touch-icon.png"]:
        shutil.copyfile(assets / name, phone / name)
    manifest = {
        "name": "Petal Reader",
        "short_name": "Petal Reader",
        "description": "Read any text or Markdown aloud with word highlighting, chapters and double-click to jump.",
        "start_url": "./",
        "scope": "./",
        "display": "standalone",
        "orientation": "any",
        "background_color": "#15121f",
        "theme_color": "#15121f",
        "icons": [
            {"src": "icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "icon-512.png", "sizes": "512x512", "type": "image/png"},
            {"src": "icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
        ],
    }
    write_text(phone / "manifest.webmanifest", json.dumps(manifest, indent=2))
    version = hashlib.sha1(page.encode("utf-8")).hexdigest()[:10]
    write_text(phone / "sw.js", SERVICE_WORKER % version)
    write_text(phone / ".nojekyll", "")


def build_all(root=ROOT):
    app_html = build_app(root)
    build_extension(root, app_html)
    vsix = package_vsix(root)
    build_phone(root, app_html)
    return vsix


def generated_paths(root=ROOT):
    pkg = json.loads((root / "vscode-extension" / "package.json").read_text(encoding="utf-8"))
    return [
        pathlib.Path("PetalReader.html"),
        pathlib.Path("vscode-extension/media/petal-preview.js"),
        pathlib.Path("vscode-extension/media/petal-preview.css"),
        pathlib.Path("vscode-extension/media/app.html"),
        pathlib.Path("vscode-extension/media/icon.png"),
        pathlib.Path("vscode-extension") / f"{pkg['name']}-{pkg['version']}.vsix",
        pathlib.Path("docs/index.html"),
        pathlib.Path("docs/manifest.webmanifest"),
        pathlib.Path("docs/sw.js"),
        pathlib.Path("docs/.nojekyll"),
        pathlib.Path("docs/icon-192.png"),
        pathlib.Path("docs/icon-512.png"),
        pathlib.Path("docs/icon-maskable-512.png"),
        pathlib.Path("docs/apple-touch-icon.png"),
    ]


def check_generated(root=ROOT):
    with tempfile.TemporaryDirectory(prefix="petal-build-") as temp_dir:
        candidate = pathlib.Path(temp_dir)
        shutil.copytree(root / "src", candidate / "src")
        shutil.copytree(root / "assets", candidate / "assets")
        shutil.copytree(root / "vscode-extension", candidate / "vscode-extension")
        build_all(candidate)
        return [
            rel for rel in generated_paths(candidate)
            if not (root / rel).exists() or (root / rel).read_bytes() != (candidate / rel).read_bytes()
        ]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify committed generated files without changing them")
    args = parser.parse_args(argv)

    if args.check:
        stale = check_generated()
        if stale:
            print("Generated files are stale:")
            for path in stale:
                print("  ", path)
            print("Run: python tools/build.py")
            return 1
        print("Generated files are up to date.")
        return 0

    vsix = build_all()
    print("Built:")
    print("  ", vsix.relative_to(ROOT))
    print("  ", pathlib.Path("vscode-extension/media"))
    print("  ", pathlib.Path("docs"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
